const PayrollRecord = require('../models/PayrollRecord');
const Employee = require('../models/Employee');
const { logActivity, sendNotification } = require('../utils/logger');

// @desc    Get payroll records
// @route   GET /api/payroll
// @access  Private (HR_ADMIN sees all, EMPLOYEE sees own only)
const getPayrollRecords = async (req, res, next) => {
  try {
    const { month, year, employeeId } = req.query;
    const query = {};

    if (req.user.role === 'EMPLOYEE') {
      if (!req.user.employee) {
        return res.status(200).json({ success: true, count: 0, records: [] });
      }
      query.employee = req.user.employee._id;
    } else if (req.user.role === 'HR_ADMIN') {
      if (employeeId) query.employee = employeeId;
    } else {
      // MANAGER has no authorization to view payroll data
      return res.status(403).json({
        success: false,
        message: 'Managers are not authorized to view salary or payroll records.'
      });
    }

    if (month) query.payPeriodMonth = parseInt(month, 10);
    if (year) query.payPeriodYear = parseInt(year, 10);

    const records = await PayrollRecord.find(query)
      .populate({
        path: 'employee',
        select: 'firstName lastName employeeCode email department designation',
        populate: [
          { path: 'department', select: 'name code' },
          { path: 'designation', select: 'title' }
        ]
      })
      .populate('processedBy', 'name')
      .sort({ payPeriodYear: -1, payPeriodMonth: -1 });

    res.status(200).json({
      success: true,
      count: records.length,
      disclaimer: 'Informational internal HR records generated by StaffSync. External bank payment gateway is not integrated.',
      records
    });
  } catch (error) {
    next(error);
  }
};

// @desc    Generate / save payroll slip
// @route   POST /api/payroll
// @access  Private (HR_ADMIN only)
const createPayrollRecord = async (req, res, next) => {
  try {
    const { employeeId, payPeriodMonth, payPeriodYear, baseSalary, allowances = [], deductions = [], paymentNote } = req.body;

    if (!employeeId || !payPeriodMonth || !payPeriodYear) {
      return res.status(400).json({
        success: false,
        message: 'Employee ID, pay period month, and pay period year are required.'
      });
    }

    const employee = await Employee.findById(employeeId);
    if (!employee) {
      return res.status(404).json({ success: false, message: 'Employee not found.' });
    }

    const totalAllowances = allowances.reduce((acc, curr) => acc + (Number(curr.amount) || 0), 0);
    const totalDeductions = deductions.reduce((acc, curr) => acc + (Number(curr.amount) || 0), 0);

    const finalBaseSalary = Number(baseSalary) || employee.baseSalary || 0;
    const grossSalary = finalBaseSalary + totalAllowances;
    const netSalary = Math.max(0, grossSalary - totalDeductions);

    // Upsert or create
    let record = await PayrollRecord.findOne({
      employee: employeeId,
      payPeriodMonth,
      payPeriodYear
    });

    if (record) {
      record.baseSalary = finalBaseSalary;
      record.allowances = allowances;
      record.deductions = deductions;
      record.grossSalary = grossSalary;
      record.totalDeductions = totalDeductions;
      record.netSalary = netSalary;
      record.paymentNote = paymentNote || '';
      record.processedBy = req.user._id;
      await record.save();
    } else {
      record = await PayrollRecord.create({
        employee: employeeId,
        payPeriodMonth,
        payPeriodYear,
        baseSalary: finalBaseSalary,
        allowances,
        deductions,
        grossSalary,
        totalDeductions,
        netSalary,
        status: 'DRAFT',
        paymentNote: paymentNote || '',
        processedBy: req.user._id
      });
    }

    await logActivity({
      actor: req.user._id,
      actorName: req.user.name,
      action: 'GENERATE_PAYROLL',
      module: 'PAYROLL',
      targetId: record._id,
      details: { employeeCode: employee.employeeCode, month: payPeriodMonth, year: payPeriodYear, netSalary },
      ipAddress: req.ip
    });

    res.status(201).json({
      success: true,
      message: 'Payroll record prepared successfully.',
      record
    });
  } catch (error) {
    next(error);
  }
};

// @desc    Update payroll status (e.g. mark PROCESSED or PAID)
// @route   PATCH /api/payroll/:id/status
// @access  Private (HR_ADMIN only)
const updatePayrollStatus = async (req, res, next) => {
  try {
    const { status, paymentNote } = req.body;
    if (!['DRAFT', 'PROCESSED', 'PAID'].includes(status)) {
      return res.status(400).json({ success: false, message: 'Invalid payroll status.' });
    }

    const record = await PayrollRecord.findById(req.params.id).populate('employee');
    if (!record) {
      return res.status(404).json({ success: false, message: 'Payroll record not found.' });
    }

    record.status = status;
    if (status === 'PAID') {
      record.paymentDate = new Date();
    }
    if (paymentNote !== undefined) {
      record.paymentNote = paymentNote;
    }
    await record.save();

    // Notify employee
    if (record.employee && record.employee.user) {
      await sendNotification({
        recipient: record.employee.user,
        title: `Payslip Status: ${status}`,
        message: `Your payslip for period ${record.payPeriodMonth}/${record.payPeriodYear} is marked as ${status}.`,
        type: 'PAYROLL',
        relatedLink: '/payroll'
      });
    }

    res.status(200).json({
      success: true,
      message: `Payroll status updated to ${status}.`,
      record
    });
  } catch (error) {
    next(error);
  }
};

module.exports = {
  getPayrollRecords,
  createPayrollRecord,
  updatePayrollStatus
};
