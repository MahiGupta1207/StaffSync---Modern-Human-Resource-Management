const mongoose = require('mongoose');

const allowanceSchema = new mongoose.Schema({
  title: { type: String, required: true },
  amount: { type: Number, required: true, min: 0 }
}, { _id: false });

const deductionSchema = new mongoose.Schema({
  title: { type: String, required: true },
  amount: { type: Number, required: true, min: 0 }
}, { _id: false });

const payrollRecordSchema = new mongoose.Schema(
  {
    employee: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Employee',
      required: [true, 'Employee reference is required for payroll record']
    },
    payPeriodMonth: {
      type: Number,
      required: [true, 'Pay period month (1-12) is required'],
      min: 1,
      max: 12
    },
    payPeriodYear: {
      type: Number,
      required: [true, 'Pay period year is required']
    },
    baseSalary: {
      type: Number,
      required: [true, 'Base salary is required'],
      min: 0
    },
    allowances: [allowanceSchema],
    deductions: [deductionSchema],
    grossSalary: {
      type: Number,
      required: true,
      min: 0
    },
    totalDeductions: {
      type: Number,
      required: true,
      min: 0
    },
    netSalary: {
      type: Number,
      required: true,
      min: 0
    },
    status: {
      type: String,
      enum: ['DRAFT', 'PROCESSED', 'PAID'],
      default: 'DRAFT'
    },
    paymentDate: {
      type: Date,
      default: null
    },
    paymentNote: {
      type: String,
      default: ''
    },
    processedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      default: null
    },
    disclaimer: {
      type: String,
      default: 'Informational internal HR record generated by StaffSync. External bank payment gateway is not integrated; disbursements must be handled through authorized corporate accounts.'
    }
  },
  {
    timestamps: true
  }
);

payrollRecordSchema.index({ employee: 1, payPeriodMonth: 1, payPeriodYear: 1 }, { unique: true });

module.exports = mongoose.model('PayrollRecord', payrollRecordSchema);
